// ACT: 返回 true 表示本次新建了 README.md；已存在时直接跳过，不覆盖用户内容。
export async function ensureWorkspaceReadme(directory: string) {
  try {
    await writeAtomic(join(directory, "README.md"), workspaceReadme, { exclusive: true });
    return true;
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "EEXIST") return false;
    console.warn(`工作区 README 写入失败：${directory}`, error);
    return false;
  }
}
